import { afterAll, beforeAll, beforeEach, describe, expect, it } from "vitest";
import type pg from "pg";
import { createOrg, createRoom, createUser, freshDatabase, truncateAll } from "./helpers/db.js";

let client: pg.Client;

beforeAll(async () => {
  client = await freshDatabase();
});
afterAll(async () => {
  await client?.end();
});
beforeEach(async () => {
  await truncateAll(client);
});

async function columns(table: string) {
  const { rows } = await client.query<{
    column_name: string;
    data_type: string;
    is_nullable: "YES" | "NO";
    column_default: string | null;
  }>(
    `SELECT column_name, data_type, is_nullable, column_default
       FROM information_schema.columns
      WHERE table_schema = 'public' AND table_name = $1`,
    [table],
  );
  return new Map(rows.map((r) => [r.column_name, r]));
}

const SPEC: Record<string, Record<string, { type: string | string[]; nullable: boolean }>> = {
  organizations: {
    id: { type: ["bigint", "uuid"], nullable: false },
    name: { type: "text", nullable: false },
    slug: { type: "text", nullable: false },
    created_at: { type: "timestamp with time zone", nullable: false },
  },
  users: {
    id: { type: ["bigint", "uuid"], nullable: false },
    email: { type: ["text", "USER-DEFINED"], nullable: false }, // USER-DEFINED = citext
    full_name: { type: "text", nullable: false },
    created_at: { type: "timestamp with time zone", nullable: false },
    updated_at: { type: "timestamp with time zone", nullable: false },
  },
  memberships: {
    organization_id: { type: ["bigint", "uuid"], nullable: false },
    user_id: { type: ["bigint", "uuid"], nullable: false },
    role: { type: ["text", "USER-DEFINED"], nullable: false }, // USER-DEFINED = enum
    created_at: { type: "timestamp with time zone", nullable: false },
  },
  rooms: {
    id: { type: ["bigint", "uuid"], nullable: false },
    organization_id: { type: ["bigint", "uuid"], nullable: false },
    name: { type: "text", nullable: false },
    capacity: { type: "integer", nullable: false },
    features: { type: "jsonb", nullable: false },
    created_at: { type: "timestamp with time zone", nullable: false },
    deleted_at: { type: "timestamp with time zone", nullable: true },
  },
  bookings: {
    id: { type: ["bigint", "uuid"], nullable: false },
    room_id: { type: ["bigint", "uuid"], nullable: false },
    organizer_id: { type: ["bigint", "uuid"], nullable: false },
    title: { type: "text", nullable: false },
    starts_at: { type: "timestamp with time zone", nullable: false },
    ends_at: { type: "timestamp with time zone", nullable: false },
    status: { type: ["text", "USER-DEFINED"], nullable: false },
    created_at: { type: "timestamp with time zone", nullable: false },
    updated_at: { type: "timestamp with time zone", nullable: false },
  },
  booking_attendees: {
    booking_id: { type: ["bigint", "uuid"], nullable: false },
    user_id: { type: ["bigint", "uuid"], nullable: false },
    response: { type: ["text", "USER-DEFINED"], nullable: false },
  },
};

describe("columns, types and nullability", () => {
  it.each(Object.keys(SPEC))("%s matches the spec", async (table) => {
    const actual = await columns(table);
    expect(actual.size, `table ${table} does not exist (or has no columns)`).toBeGreaterThan(0);
    for (const [name, spec] of Object.entries(SPEC[table]!)) {
      const col = actual.get(name);
      expect(col, `${table}.${name} is missing`).toBeDefined();
      const types = Array.isArray(spec.type) ? spec.type : [spec.type];
      expect(types, `${table}.${name} should be ${types.join(" or ")}, is ${col?.data_type}`).toContain(
        col?.data_type,
      );
      expect(col?.is_nullable, `${table}.${name} should be ${spec.nullable ? "nullable" : "NOT NULL"}`).toBe(
        spec.nullable ? "YES" : "NO",
      );
    }
  });

  it("no column uses timestamp WITHOUT time zone", async () => {
    const { rows } = await client.query(
      `SELECT table_name, column_name FROM information_schema.columns
        WHERE table_schema = 'public' AND data_type = 'timestamp without time zone'`,
    );
    expect(rows, "use timestamptz for points in time").toEqual([]);
  });
});

describe("generated keys and defaults", () => {
  it("ids are generated by the database", async () => {
    const orgId = await createOrg(client);
    const userId = await createUser(client);
    const roomId = await createRoom(client, orgId);
    for (const id of [orgId, userId, roomId]) expect(id, "INSERT … RETURNING id gave nothing").toBeTruthy();
  });

  it("created_at / updated_at default to now()", async () => {
    await createUser(client, "ts@example.com");
    const { rows } = await client.query(
      "SELECT created_at, updated_at, now() - created_at < interval '1 minute' AS recent FROM users",
    );
    expect(rows[0].created_at).toBeInstanceOf(Date);
    expect(rows[0].updated_at).toBeInstanceOf(Date);
    expect(rows[0].recent).toBe(true);
  });

  it("rooms.features defaults to an empty JSON object, deleted_at to NULL", async () => {
    const roomId = await createRoom(client, await createOrg(client));
    const { rows } = await client.query("SELECT features, deleted_at FROM rooms WHERE id = $1", [roomId]);
    expect(rows[0]).toEqual({ features: {}, deleted_at: null });
  });

  it("memberships.role defaults to 'member', bookings.status to 'confirmed', attendee response to 'pending'", async () => {
    const orgId = await createOrg(client);
    const userId = await createUser(client);
    await client.query("INSERT INTO memberships (organization_id, user_id) VALUES ($1, $2)", [orgId, userId]);
    const roomId = await createRoom(client, orgId);
    const { rows: b } = await client.query(
      `INSERT INTO bookings (room_id, organizer_id, title, starts_at, ends_at)
       VALUES ($1, $2, 'Standup', '2026-12-01 09:00Z', '2026-12-01 09:15Z') RETURNING id, status`,
      [roomId, userId],
    );
    await client.query("INSERT INTO booking_attendees (booking_id, user_id) VALUES ($1, $2)", [b[0].id, userId]);

    const role = await client.query("SELECT role::text FROM memberships");
    const response = await client.query("SELECT response::text FROM booking_attendees");
    expect(role.rows[0].role).toBe("member");
    expect(b[0].status).toBe("confirmed");
    expect(response.rows[0].response).toBe("pending");
  });
});
