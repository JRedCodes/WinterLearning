-- Shopfront e-commerce schema used by every exercise in this module.
-- Loaded into a fresh `public` schema by test/globalSetup.ts (and `make seed`).

CREATE TABLE categories (
  id        integer PRIMARY KEY,
  name      text    NOT NULL UNIQUE,
  parent_id integer REFERENCES categories (id)       -- NULL = top-level category
);

CREATE TABLE customers (
  id         integer     PRIMARY KEY,
  email      text        NOT NULL UNIQUE,
  full_name  text        NOT NULL,
  city       text,                                   -- NULL = unknown
  created_at timestamptz NOT NULL
);

CREATE TABLE products (
  id          integer       PRIMARY KEY,
  name        text          NOT NULL UNIQUE,
  category_id integer       REFERENCES categories (id), -- NULL = uncategorised
  price       numeric(10,2) NOT NULL CHECK (price >= 0),
  active      boolean       NOT NULL DEFAULT true
);

CREATE TABLE orders (
  id          integer     PRIMARY KEY,
  customer_id integer     NOT NULL REFERENCES customers (id),
  status      text        NOT NULL
              CHECK (status IN ('pending', 'paid', 'shipped', 'delivered', 'cancelled')),
  ordered_at  timestamptz NOT NULL,
  shipped_at  timestamptz                             -- NULL = not shipped (yet)
);

CREATE TABLE order_items (
  order_id   integer       NOT NULL REFERENCES orders (id),
  product_id integer       NOT NULL REFERENCES products (id),
  quantity   integer       NOT NULL CHECK (quantity > 0),
  unit_price numeric(10,2) NOT NULL,                  -- price at the time of purchase
  PRIMARY KEY (order_id, product_id)
);

CREATE TABLE reviews (
  id          integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id  integer     NOT NULL REFERENCES products (id),
  customer_id integer     NOT NULL REFERENCES customers (id),
  rating      integer     NOT NULL CHECK (rating BETWEEN 1 AND 5),
  body        text,
  created_at  timestamptz NOT NULL DEFAULT now(),
  UNIQUE (product_id, customer_id)                    -- one review per customer per product
);
